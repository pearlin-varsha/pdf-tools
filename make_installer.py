"""
make_installer.py - writes installer.iss for you.

The right-click menu needs 3-4 registry lines per menu item per file type
(about 140 lines). Typing that by hand invites typos, so this script generates
it from the small MENUS table below.

You only need to run this if you change MENUS (add a file type or feature):
    python make_installer.py
"""

from pathlib import Path

VERSION = "2.0"

IMAGE_TYPES = [".jpg", ".jpeg", ".png", ".bmp", ".gif", ".tif", ".tiff", ".webp"]
OFFICE_TYPES = [".doc", ".docx", ".rtf", ".odt", ".ppt", ".pptx", ".odp", ".xls", ".xlsx", ".ods"]
PDF_TYPES = [".pdf"]

# Each menu item: (key, text shown, command passed to PDFTools.exe)
# Explorer sorts items by KEY alphabetically, so the number prefix sets the order.
CONVERT_IMG = ("01convert", "Convert to PDF", "img2pdf")
CONVERT_OFFICE = ("01convert", "Convert to PDF", "office2pdf")
MERGE = ("02merge", "Merge into one PDF", "merge")
COMPRESS = ("03compress", "Compress PDF", "compress")
SPLIT = ("04split", "Split / extract pages", "split")
TO_IMAGES = ("05pdf2img", "Convert pages to images", "pdf2img")

# Which items appear for which file types
MENUS = [
    (IMAGE_TYPES, [CONVERT_IMG, MERGE]),
    (OFFICE_TYPES, [CONVERT_OFFICE]),
    (PDF_TYPES, [MERGE, COMPRESS, SPLIT, TO_IMAGES]),
]

# File types v1 added a single "Convert to PDF" item to - removed during upgrade.
V1_TYPES = [".jpg", ".jpeg", ".png", ".bmp", ".gif", ".tif", ".tiff", ".webp"]

BASE = r"Software\Classes\SystemFileAssociations"
EXE = r'""{app}\PDFTools.exe""'          # Inno needs "" for each " inside a value


def reg(subkey, name, data, flags=""):
    """One [Registry] line. name "" = the key's (Default) value."""
    line = f'Root: HKCU; Subkey: "{subkey}"; ValueType: string; ValueName: "{name}"; ValueData: "{data}"'
    return line + (f"; Flags: {flags}" if flags else "")


def delete_key(subkey):
    """A line that deletes a key (and everything under it) before installing."""
    return f'Root: HKCU; Subkey: "{subkey}"; ValueType: none; Flags: deletekey'


def registry_section():
    lines = ["; --- Remove v1's single menu item (it's now inside the submenu) ---"]
    lines += [delete_key(rf"{BASE}\{ext}\shell\PDFTools.ToPdf") for ext in V1_TYPES]

    for types, items in MENUS:
        for ext in types:
            parent = rf"{BASE}\{ext}\shell\PDFTools"
            lines += ["", f"; --- {ext} ---",
                      delete_key(parent),                              # clear old items from earlier versions
                      reg(parent, "MUIVerb", "PDF Tools", "uninsdeletekey"),  # submenu title
                      reg(parent, "Icon", EXE),
                      reg(parent, "SubCommands", ""),                  # "this item opens a submenu"
                      reg(parent, "MultiSelectModel", "Player")]       # allow more than 15 selected files
            for key, label, command in items:
                item = rf"{parent}\shell\{key}"
                lines += [reg(item, "MUIVerb", label),
                          reg(item, "MultiSelectModel", "Player"),
                          reg(rf"{item}\command", "", f'{EXE} {command} ""%1""')]
    return "\n".join(lines)


TEMPLATE = r"""; ------------------------------------------------------------------
;  Inno Setup script for PDF Tools  (GENERATED by make_installer.py - edit that instead)
;  Open in Inno Setup and press Compile (Ctrl+F9) AFTER running build.bat.
; ------------------------------------------------------------------

[Setup]
; Same AppId as v1, so installing this upgrades v1 instead of adding a second copy.
AppId={{6E3B1C2A-8F4D-4B7A-9C21-5D0E7A4F3B19}
AppName=PDF Tools
AppVersion=__VERSION__
AppPublisher=Pearlin
DefaultDirName={autopf}\PDF Tools
DefaultGroupName=PDF Tools
; No admin rights needed: installs for the current user only
PrivilegesRequired=lowest
OutputDir=installer_output
OutputBaseFilename=PDFTools-Setup-__VERSION__
Compression=lzma2
SolidCompression=yes
; Makes Explorer refresh its right-click menus right after install/uninstall
ChangesAssociations=yes
UninstallDisplayIcon={app}\PDFTools.exe
; If PDFTools.exe is somehow running during an upgrade, close it
CloseApplications=yes

[InstallDelete]
; Clear out the previous version's files so nothing stale is left behind
Type: filesandordirs; Name: "{app}\_internal"

[Files]
Source: "dist\PDFTools\*"; DestDir: "{app}"; Flags: ignoreversion recursesubdirs createallsubdirs

[Registry]
; How the submenu works, per file type (e.g. .pdf):
;   ...\.pdf\shell\PDFTools                 MUIVerb="PDF Tools", SubCommands=""  -> the "PDF Tools >" entry
;   ...\.pdf\shell\PDFTools\shell\03compress MUIVerb="Compress PDF"               -> an item inside it
;   ...\.pdf\shell\PDFTools\shell\03compress\command = "PDFTools.exe" compress "%1"
; %1 is replaced by the file you right-clicked.
__REGISTRY__

[Icons]
Name: "{group}\Uninstall PDF Tools"; Filename: "{uninstallexe}"
"""


if __name__ == "__main__":
    text = TEMPLATE.replace("__VERSION__", VERSION).replace("__REGISTRY__", registry_section())
    out = Path(__file__).with_name("installer.iss")
    out.write_text(text, encoding="utf-8")
    print(f"Wrote {out}")
